PAGE_W, PAGE_H = A4
MARGIN = 16 * mm
CONTENT_W = PAGE_W - 2 * MARGIN
HEADER_H = 30 * mm          # space reserved at the top of every page for the letterhead

INK = colors.HexColor("#111827")
TEXT = colors.HexColor("#374151")
MUTED = colors.HexColor("#6b7280")
RULE = colors.HexColor("#d1d5db")
HAIRLINE = colors.HexColor("#e5e7eb")
HEAD_BG = colors.HexColor("#f3f4f6")
ACCENT = colors.HexColor("#174a8b")
DANGER = colors.HexColor("#b91c1c")

FONT, BOLD = "Helvetica", "Helvetica-Bold"

SMALL = ParagraphStyle("small", fontName=FONT, fontSize=8, leading=10, textColor=TEXT)
SMALL_MUTED = ParagraphStyle("small_muted", parent=SMALL, textColor=MUTED)
NORMAL = ParagraphStyle("norm", fontName=FONT, fontSize=9, leading=12, textColor=TEXT)
LABEL = ParagraphStyle("label", fontName=BOLD, fontSize=7, leading=9, textColor=MUTED, spaceAfter=2)
CELL = ParagraphStyle("cell", fontName=FONT, fontSize=8.5, leading=10.5, textColor=INK)
CELL_SUB = ParagraphStyle("cell_sub", parent=CELL, fontSize=7.5, leading=9, textColor=MUTED)


def money(value):
    return "{:,.2f}".format(float(value or 0))


def _esc(text):
    return xml_escape(str(text or ""))


def _qr_drawing(value, size=22 * mm):
    widget = qr.QrCodeWidget(value)
    widget.barFillColor = INK
    x1, y1, x2, y2 = widget.getBounds()
    d = Drawing(size, size, transform=[size / (x2 - x1), 0, 0, size / (y2 - y1), 0, 0])
    d.add(widget)
    return d


class _NumberedCanvas(canvas_mod.Canvas):
    """Canvas that knows the total page count, so the footer can say 'Page 2 of 5'."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved = []

    def showPage(self):
        self._saved.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved)
        for state in self._saved:
            self.__dict__.update(state)
            self.saveState()
            self.setFont(FONT, 7.5)
            self.setFillColor(MUTED)
            self.drawRightString(PAGE_W - MARGIN, 10 * mm, "Page %d of %d" % (self._pageNumber, total))
            self.restoreState()
            super().showPage()
        super().save()


def _page_decor(doc_title, reference):
    """Letterhead and footer drawn on every page."""
    company = get_setting("company_name")
    address = get_setting("company_address")
    generated = datetime.now().strftime("%Y-%m-%d %H:%M")

    def draw(c, doc):
        c.saveState()
        top = PAGE_H - MARGIN
        # Company block (left)
        c.setFillColor(ACCENT)
        c.rect(MARGIN, top - 5.2 * mm, 3.2 * mm, 5.2 * mm, stroke=0, fill=1)
        c.setFillColor(INK)
        c.setFont(BOLD, 11)
        c.drawString(MARGIN + 5 * mm, top - 4.3 * mm, company)
        c.setFont(FONT, 8)
        c.setFillColor(MUTED)
        c.drawString(MARGIN + 5 * mm, top - 9 * mm, address)
        # Document title and reference (right)
        c.setFillColor(INK)
        c.setFont(BOLD, 15)
        c.drawRightString(PAGE_W - MARGIN, top - 5 * mm, doc_title.upper())
        if reference:
            c.setFont(FONT, 9)
            c.setFillColor(TEXT)
            c.drawRightString(PAGE_W - MARGIN, top - 10 * mm, reference)
        # Rule under the letterhead
        c.setStrokeColor(INK)
        c.setLineWidth(0.8)
        c.line(MARGIN, top - 14 * mm, PAGE_W - MARGIN, top - 14 * mm)
        # Footer
        c.setStrokeColor(HAIRLINE)
        c.setLineWidth(0.5)
        c.line(MARGIN, 14 * mm, PAGE_W - MARGIN, 14 * mm)
        c.setFont(FONT, 7.5)
        c.setFillColor(MUTED)
        c.drawString(MARGIN, 10 * mm, "%s  ·  %s%s  ·  Generated by i-STOCK %s" % (
            company, doc_title, (" " + reference) if reference else "", generated))
        c.restoreState()
    return draw


def _build(story, doc_title, reference=None):
    buf = io.BytesIO()
    # Frames pad their content by 6pt; offset the margins so content lines up with the letterhead.
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=MARGIN - 6, rightMargin=MARGIN - 6,
                            topMargin=MARGIN + HEADER_H - 12 * mm, bottomMargin=20 * mm,
                            title="%s %s" % (doc_title, reference or ""), author=get_setting("company_name"),
                            creator="i-STOCK")
    decor = _page_decor(doc_title, reference)
    doc.build(story, onFirstPage=decor, onLaterPages=decor, canvasmaker=_NumberedCanvas)
    buf.seek(0)
    return buf


def _info_block(left, right):
    """Two-column block: a party address (left) and document facts (right).

    `left`  = (label, [lines])            e.g. ("SUPPLIER", ["Acme", "Colombo"])
    `right` = [(label, value), ...]       e.g. [("PO number", "PO-0001"), ...]
    """
    label, lines = left
    party = [Paragraph(_esc(label).upper(), LABEL)]
    if lines:
        party.append(Paragraph("<b>%s</b>" % _esc(lines[0]), NORMAL))
        party += [Paragraph(_esc(x), NORMAL) for x in lines[1:] if x]
    facts = Table([[Paragraph(_esc(k), SMALL_MUTED), Paragraph(_esc(v), ParagraphStyle("fv", parent=NORMAL, alignment=TA_RIGHT))]
                   for k, v in right], colWidths=[32 * mm, 48 * mm])
    facts.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 1.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5),
        ("LINEBELOW", (0, 0), (-1, -2), 0.4, HAIRLINE),
    ]))
    outer = Table([[party, facts]], colWidths=[CONTENT_W - 80 * mm, 80 * mm])
    outer.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                               ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0)]))
    return [outer, Spacer(1, 7 * mm)]


def _table(data, widths, right_cols=(), center_cols=(), extra=None, total_rows=0):
    """Ruled data table: grey header, hairlines between rows, no vertical lines."""
    t = Table(data, colWidths=widths, repeatRows=1)
    body_end = -1 - total_rows
    style = [
        ("FONTNAME", (0, 0), (-1, 0), BOLD),
        ("FONTSIZE", (0, 0), (-1, 0), 7.5),
        ("TEXTCOLOR", (0, 0), (-1, 0), TEXT),
        ("BACKGROUND", (0, 0), (-1, 0), HEAD_BG),
        ("FONTNAME", (0, 1), (-1, -1), FONT),
        ("FONTSIZE", (0, 1), (-1, -1), 8.5),
        ("TEXTCOLOR", (0, 1), (-1, -1), INK),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("LINEABOVE", (0, 0), (-1, 0), 0.6, RULE),
        ("LINEBELOW", (0, 0), (-1, 0), 0.6, RULE),
        ("LINEBELOW", (0, 1), (-1, body_end), 0.4, HAIRLINE),
    ]
    for c in right_cols:
        style.append(("ALIGN", (c, 0), (c, -1), "RIGHT"))
    for c in center_cols:
        style.append(("ALIGN", (c, 0), (c, -1), "CENTER"))
    if total_rows:
        first = len(data) - total_rows
        style += [("LINEABOVE", (0, first), (-1, first), 0.8, INK),
                  ("FONTNAME", (0, -1), (-1, -1), BOLD),
                  ("TOPPADDING", (0, first), (-1, -1), 5)]
    style.extend(extra or [])
    t.setStyle(TableStyle(style))
    return t


def _item_cell(sku, name):
    return [Paragraph(_esc(name), CELL), Paragraph(_esc(sku), CELL_SUB)]


def _signatures(*labels):
    cells = [[Spacer(1, 12 * mm) for _ in labels],
             [Paragraph("%s<br/><font color='#6b7280' size='7'>Name, signature and date</font>" % _esc(l), SMALL)
              for l in labels]]
    gap = 8 * mm
    w = (CONTENT_W - gap * (len(labels) - 1)) / len(labels)
    widths = []
    for i in range(len(labels)):
        widths.append(w)
        if i < len(labels) - 1:
            widths.append(gap)
    rows = []
    for r in cells:
        row = []
        for i, c in enumerate(r):
            row.append(c)
            if i < len(r) - 1:
                row.append("")
        rows.append(row)
    t = Table(rows, colWidths=widths)
    style = [("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0)]
    for i in range(0, len(widths), 2):
        style.append(("LINEABOVE", (i, 1), (i, 1), 0.6, INK))
    t.setStyle(TableStyle(style))
    return KeepTogether([Spacer(1, 12 * mm), t])


def _note(text):
    return [Spacer(1, 5 * mm), Paragraph(text, SMALL_MUTED)]


def _date(value):
    return value.strftime("%Y-%m-%d") if value else "-"


