def reorder_xlsx(items):
    headers = ["SKU", "Item", "Supplier", "On hand", "Avg daily sales", "Demand std dev", "Lead time (d)",
               "Safety stock", "Reorder point", "Forecast 30d", "Model", "Recommended qty", "Unit cost", "Order value"]
    rows = []
    for i in items:
        lt = i.lead_time_override or (i.supplier.lead_time_days if i.supplier else None)
        rows.append([i.sku, i.name, i.supplier.name if i.supplier else "", i.quantity_on_hand,
                     round(i.avg_daily_sales, 2), round(i.demand_std, 2), lt, i.safety_stock, i.reorder_point,
                     round(i.forecast_30d, 1), i.forecast_model, i.recommended_qty, float(i.unit_cost),
                     round(float(i.unit_cost) * i.recommended_qty, 2)])
    return _workbook("Reorder Recommendations", headers, rows, [14, 32, 26, 10, 14, 14, 12, 12, 12, 12, 8, 15, 11, 13])
