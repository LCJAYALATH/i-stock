def purchase_order_pdf(po):
    cur = get_setting("currency")
    s = po.supplier
    story = _info_block(
        ("Supplier", [s.name, s.contact_person and "Attn: " + s.contact_person, s.address, s.phone, s.email]),
        [("PO number", po.po_number), ("Order date", _date(po.sent_at or po.created_at)),
         ("Expected delivery", _date(po.expected_date)), ("Status", po.status.title()),
         ("Currency", cur)])
    data = [["#", "Item", "Qty", "Unit cost", "Amount"]]
    for i, l in enumerate(po.lines, 1):
        data.append([i, _item_cell(l.item.sku, l.item.name), "{:,}".format(l.quantity_ordered),
                     money(l.unit_cost), money(float(l.unit_cost) * l.quantity_ordered)])
    if not po.lines:
        data.append(["", Paragraph("No lines on this order.", SMALL_MUTED), "", "", ""])
    data.append(["", "", "", "Total (%s)" % cur, money(po.total)])
    story.append(_table(data, [9 * mm, CONTENT_W - 9 * mm - 20 * mm - 30 * mm - 32 * mm, 20 * mm, 30 * mm, 32 * mm],
                        right_cols=(2, 3, 4), total_rows=1))
    if po.notes:
        story += _note("<b>Notes:</b> " + _esc(po.notes))
    story += _note("Please quote the PO number on the delivery note and invoice. Goods are received against this order "
                   "and checked for quantity, batch number and expiry date.")
    approver = po.approved_by.full_name if po.approved_by else ""
    story.append(_signatures("Approved by" + (": " + approver if approver else ""), "Received by"))
    return _build(story, "Purchase order", po.po_number)


def picking_list_pdf(order, plan):
    c = order.client
    story = _info_block(
        ("Deliver to", [c.name, c.contact_person and "Attn: " + c.contact_person, c.address, c.phone]),
        [("Order", order.order_number), ("Order date", _date(order.created_at)),
         ("Lines", str(len(order.lines))), ("Pick sequence", "By bin, FEFO batches")])
    data = [["Bin", "Scan", "Item", "Batch", "Expiry", "Qty", "Picked"]]
    short_rows = []
    for p in plan:
        item = p["line"].item
        allocs = p["allocations"] or [{"batch": None, "qty": 0}]
        for a in allocs:
            b = a["batch"]
            data.append([p["location"] if p["location"] != "ZZZ" else "-", _qr_drawing(item.scan_code, 13 * mm),
                         _item_cell(item.sku, item.name), b.batch_no if b else "NO STOCK",
                         _date(b.expiry_date) if b else "-", a["qty"], ""])
        if p["short"]:
            short_rows.append(len(data))
            data.append(["", "", Paragraph("<font color='#b91c1c'><b>Short by %d</b> - not enough stock</font>" % p["short"], CELL),
                         "", "", "", ""])
    extra = [("FONTNAME", (0, 1), (0, -1), BOLD), ("FONTNAME", (5, 1), (5, -1), BOLD)]
    # A box to tick/write the picked quantity
    for r in range(1, len(data)):
        if r not in short_rows:
            extra.append(("BOX", (6, r), (6, r), 0.6, RULE))
    for r in short_rows:
        extra.append(("BACKGROUND", (0, r), (-1, r), colors.HexColor("#fef2f2")))
    story.append(_table(data, [16 * mm, 17 * mm, CONTENT_W - 16 * mm - 17 * mm - 28 * mm - 22 * mm - 14 * mm - 20 * mm,
                               28 * mm, 22 * mm, 14 * mm, 20 * mm], right_cols=(5,), extra=extra))
    story.append(_signatures("Picked by", "Checked by", "Received by (client)"))
    return _build(story, "Picking list", order.order_number)


def invoice_pdf(order):
    cur = get_setting("currency")
    c = order.client
    number = order.order_number.replace("SO", "INV")
    story = _info_block(
        ("Bill to", [c.name, c.contact_person and "Attn: " + c.contact_person, c.address, c.phone]),
        [("Invoice number", number), ("Invoice date", _date(order.dispatched_at or order.created_at)),
         ("Order reference", order.order_number), ("Currency", cur)])
    data = [["#", "Item", "Qty", "Unit price", "Amount"]]
    for i, l in enumerate(order.lines, 1):
        data.append([i, _item_cell(l.item.sku, l.item.name), "{:,}".format(l.quantity),
                     money(l.unit_price), money(float(l.unit_price) * l.quantity)])
    data.append(["", "", "", "Total due (%s)" % cur, money(order.total)])
    story.append(_table(data, [9 * mm, CONTENT_W - 9 * mm - 20 * mm - 30 * mm - 34 * mm, 20 * mm, 30 * mm, 34 * mm],
                        right_cols=(2, 3, 4), total_rows=1))
    story += _note("Goods dispatched against order %s. Please quote the invoice number with your payment." % order.order_number)
    story.append(_signatures("Issued by", "Received by"))
    return _build(story, "Invoice", number)


def count_sheet_pdf(items, show_system_qty=False):
    story = _info_block(
        ("Instructions", ["Physical stock count",
                          "Scan each barcode, count the units in the bin and write the quantity.",
                          "Record damaged or expired stock in Notes."]),
        [("Count date", "____________________"), ("Counted by", "____________________"),
         ("Mode", "With system quantity" if show_system_qty else "Blind count"), ("Items", str(len(items)))])
    head = ["Bin", "Barcode", "Item", "Unit"]
    if show_system_qty:
        head.append("System")
    head += ["Counted", "Notes"]
    data = [head]
    for item in sorted(items, key=lambda i: ((i.location.code if i.location else "ZZZ"), i.sku)):
        bc = code128.Code128(item.scan_code, barHeight=7 * mm, barWidth=0.26 * mm, humanReadable=True, fontSize=6)
        row = [item.location.code if item.location else "-", bc, _item_cell(item.sku, item.name), item.unit]
        if show_system_qty:
            row.append(item.quantity_on_hand)
        row += ["", ""]
        data.append(row)
    fixed = [16 * mm, 46 * mm, 12 * mm] + ([16 * mm] if show_system_qty else []) + [20 * mm, 26 * mm]
    widths = fixed[:2] + [CONTENT_W - sum(fixed)] + fixed[2:]
    counted_col = len(head) - 2
    extra = [("FONTNAME", (0, 1), (0, -1), BOLD)]
    for r in range(1, len(data)):
        extra.append(("BOX", (counted_col, r), (counted_col, r), 0.6, RULE))
    story.append(_table(data, widths, right_cols=(4,) if show_system_qty else (), extra=extra))
    story.append(_signatures("Counted by", "Verified by"))
    return _build(story, "Stock count sheet", datetime.now().strftime("%Y-%m-%d"))


def labels_pdf(items):
    """A4 sheet of item labels (3 x 7) with a QR code and a Code128 barcode."""
    name_style = ParagraphStyle("lbl_name", parent=CELL, fontSize=8, leading=9.5)
    sku_style = ParagraphStyle("lbl_sku", fontName=BOLD, fontSize=9, leading=11, textColor=INK)
    cells = []
    for item in items:
        bc = code128.Code128(item.scan_code, barHeight=7 * mm, barWidth=0.22 * mm, humanReadable=True, fontSize=6)
        bin_code = item.location.code if item.location else ""
        inner = Table([[_qr_drawing(item.scan_code, 19 * mm),
                        [Paragraph(_esc(item.sku), sku_style), Paragraph(_esc(item.name[:44]), name_style),
                         Paragraph(("Bin %s · %s" % (bin_code, item.unit)) if bin_code else _esc(item.unit), SMALL_MUTED),
                         Spacer(1, 1.5 * mm), bc]]],
                      colWidths=[21 * mm, 39 * mm])
        inner.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                                   ("LEFTPADDING", (0, 0), (-1, -1), 1), ("RIGHTPADDING", (0, 0), (-1, -1), 1)]))
        cells.append(inner)
    rows = [cells[i:i + 3] for i in range(0, len(cells), 3)] or [[""]]
    if len(rows[-1]) < 3:
        rows[-1] += [""] * (3 - len(rows[-1]))
    t = Table(rows, colWidths=[CONTENT_W / 3] * 3, rowHeights=[33 * mm] * len(rows))
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.3, HAIRLINE),  # light cut guides
                           ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    return _build([t], "Item labels", "%d items" % len(items))


